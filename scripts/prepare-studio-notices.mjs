async function hashFiles(root) {
  for (const entry of await readdir(root, { withFileTypes: true })) {
    const path = join(root, entry.name),
      details = await lstat(path);
    if (details.isSymbolicLink())
      throw new Error(`Refusing linked Studio component: ${path}`);
    if (details.isDirectory()) await hashFiles(path);
    else if (details.isFile() && path !== join(studio, "manifest.json"))
      files.push({
        path: relative(studio, path).split(sep).join("/"),
        sha256: createHash("sha256")
          .update(await readFile(path))
          .digest("hex"),
      });
  }
}
